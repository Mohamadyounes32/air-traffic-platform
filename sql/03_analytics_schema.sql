CREATE TABLE IF NOT EXISTS analytics.dim_hour (
    hour_key  SMALLINT PRIMARY KEY,   -- 0..23
    hour_label TEXT    NOT NULL,      -- '06:00'
    day_part  TEXT     NOT NULL       -- Night / Morning / Afternoon / Evening
);

INSERT INTO analytics.dim_hour
SELECT h, lpad(h::text, 2, '0') || ':00',
       CASE WHEN h < 6 THEN 'Night' WHEN h < 12 THEN 'Morning'
            WHEN h < 18 THEN 'Afternoon' ELSE 'Evening' END
FROM generate_series(0, 23) AS h
ON CONFLICT (hour_key) DO NOTHING;

