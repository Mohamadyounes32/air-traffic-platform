    EXTRACT(MONTH   FROM d)::smallint,
    (ARRAY['January','February','March','April','May','June','July',
           'August','September','October','November','December'])[EXTRACT(MONTH FROM d)::int],
    EXTRACT(DAY     FROM d)::smallint,
    EXTRACT(WEEK    FROM d)::smallint,
    EXTRACT(ISODOW  FROM d)::smallint,
    (ARRAY['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'])[EXTRACT(ISODOW FROM d)::int],
    EXTRACT(ISODOW  FROM d) >= 6,
    CASE WHEN EXTRACT(MONTH FROM d) IN (12, 1, 2) THEN 'Winter'
         WHEN EXTRACT(MONTH FROM d) IN (3, 4, 5)  THEN 'Spring'
         WHEN EXTRACT(MONTH FROM d) IN (6, 7, 8)  THEN 'Summer'
         ELSE 'Autumn' END,
    FALSE,
    NULL
FROM generate_series(DATE '2024-01-01', DATE '2026-12-31', INTERVAL '1 day') AS d
ON CONFLICT (date_key) DO NOTHING;

